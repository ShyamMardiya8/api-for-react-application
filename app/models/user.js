const mongoose = require("mongoose");

const userInformationSchema = new mongoose.Schema({
  firstName: {
    type: String,
    require: true,
    trim: true,
  },
  lastName: {
    type: String,
    require: true,
    trim: true,
  },
  phoneNumber: {
    type: String,
    require: true,
    trim: true,
  },
  email: {
    type: String,
    require: true,
    trim: true,
  },
});


const userInformation = mongoose.model("userInformation", userInformationSchema)


module.exports = userInformation